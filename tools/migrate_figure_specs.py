#!/usr/bin/env python3
"""Add the V7.6 evidence contract to legacy FigureSpecs without changing geometry."""
from __future__ import annotations

import json
from pathlib import Path

from scientific_ir import ROOT, enrich_spec, validate_spec


def main():
    for path in sorted((ROOT / "figure_specs").rglob("*.json")):
        if path.stem == "C01_composite_defense_slide":
            continue  # This file is generated by build_c01_v74.py.
        before = json.loads(path.read_text(encoding="utf-8"))
        after = enrich_spec(before)
        validate_spec(after)
        path.write_text(json.dumps(after, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"Migrated {path.relative_to(ROOT)} ({len(after['elements'])} elements)")


if __name__ == "__main__":
    main()
